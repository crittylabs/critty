func TestDoctorTerminalMarker(t *testing.T) {
	old := lookPath
	oldProbe := probeDoctorMarker
	lookPath = func(name string) (string, error) { return "", exec.ErrNotFound }
	t.Cleanup(func() { lookPath, probeDoctorMarker = old, oldProbe })
	for _, mode := range []string{"unprobed", "local", "local failure", "invalid", "notified", "legacy"} {
		t.Run(mode, func(t *testing.T) {
			t.Setenv("XDG_STATE_HOME", t.TempDir())
			var id string
			want := "info"
			probeDoctorMarker = func(origin terminalbinding.Origin) (markerProbeResult, error) {
				if mode == "local" {
					return markerProbeResult{Checked: true, Target: terminalbinding.Target{Kind: "tmux", Origin: origin}}, nil
				}
				if mode == "local failure" {
					return markerProbeResult{}, errors.New("cannot read pane")
				}
				return markerProbeResult{Reason: "no current TTY available"}, nil
			}
			if mode == "local" {
				want = "ok"
			} else if mode == "local failure" {
				want = "warn"
			}
			if mode == "invalid" {
				id, want = "invalid", "warn"
			}
			if mode == "notified" || mode == "legacy" {
				store := terminalbinding.DefaultStore()
				request, err := store.Prepare()
				if err != nil {
					t.Fatal(err)
				}
				target := terminalbinding.Target{Kind: "terminal", Origin: terminalbinding.Origin{PID: os.Getpid(), Started: "test"}}
				if mode == "legacy" {
					target = terminalbinding.Target{Kind: "tmux", Socket: "/unused/socket", Pane: "%1"}
				}
				if err := store.Notify(request.ID, target); err != nil {
					t.Fatal(err)
				}
				id, want = request.ID, "ok"
			}
			r := doctorReport{}
			r.checkTerminalBinding(id, mode == "notified")
			if d := diagnosticFor(t, r, "terminal/marker"); d.Status != want {
				t.Fatalf("marker: %+v", d)
			}
			for _, d := range r.Checks {
				if d.Check == "terminal/tfil-session" {
					t.Fatalf("process ancestry must not be a separate diagnostic: %+v", d)
				}
			}
			if d := diagnosticFor(t, r, "terminal/tfil"); d.Status != "info" || d.Advice != "" {
				t.Fatalf("missing optional filter must not request remediation: %+v", d)
			}
			if id != "" && want == "ok" {
				r = doctorReport{}
				r.checkTerminalBinding(id, mode == "notified")
				if d := diagnosticFor(t, r, "terminal/marker"); d.Status != "warn" {
					t.Fatalf("request reused: %+v", d)
				}
			}
		})
	}
}

func TestDoctorCodexWrapper(t *testing.T) {
	wrapper := filepath.Join(t.TempDir(), "codex")
	cmd := exec.Command("go", "build", "-o", wrapper, "../../cmd/codex")
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	tfilWrapper := filepath.Join(t.TempDir(), "codex")
	if err := os.WriteFile(tfilWrapper, []byte("#!/bin/sh\n# tfil-wrapper\n# Generated by tfil 0.4.1.\nexec tfil --wrap=\"$0\" --critty-notify -- \"$@\"\n"), 0755); err != nil {
		t.Fatal(err)
	}
	alias := filepath.Join(t.TempDir(), "codex")
	if err := os.Symlink(tfilWrapper, alias); err != nil {
		t.Fatal(err)
	}
	old := lookPath
	t.Cleanup(func() { lookPath = old })
	for _, tt := range []struct{ name, path, want string }{
		{"missing", "", "info"},
		{"shim", "/bin/sh", "info"},
		{"wrapper", wrapper, "ok"},
		{"tfil", tfilWrapper, "ok"},
		{"tfil symlink", alias, "ok"},
	} {
		t.Run(tt.name, func(t *testing.T) {
			lookPath = func(string) (string, error) {
				if tt.path == "" {
					return "", exec.ErrNotFound
				}
				return tt.path, nil
			}
			r := doctorReport{}
			r.checkCodexWrapper()
			if d := diagnosticFor(t, r, "terminal/codex-wrapper"); d.Status != tt.want {
				t.Fatalf("wrapper: %+v", d)
			}
			if strings.HasPrefix(tt.name, "tfil") && !strings.Contains(r.Checks[0].Message, "tfil-generated") {
				t.Fatalf("wrong wrapper identity: %+v", r.Checks[0])
			}
		})
	}
}

func TestTfilAncestor(t *testing.T) {
	for _, tt := range []struct {
		name    string
		parent  int
		command string
		fail    bool
		want    int
	}{
		{"direct", 1, "/usr/local/bin/tfil", false, 20},
		{"ancestor", 10, "codex", false, 10},
		{"absent", 1, "codex", false, 0},
		{"cycle", 20, "codex", false, 0},
		{"error", 1, "", true, 0},
		{"similar name", 1, "tfil-other", false, 0},
	} {
		t.Run(tt.name, func(t *testing.T) {
			got, err := tfilAncestor(20, func(pid int) (int, string, error) {
				if tt.fail {
					return 0, "", errors.New("denied")
				}
				if pid == 10 {
					return 1, "tfil", nil
				}
				return tt.parent, tt.command, nil
			})
			if got != tt.want || (err != nil) != tt.fail {
				t.Fatalf("got %d, %v", got, err)
			}
		})
	}
	// A process beyond the bounded ancestry must not be identified.
	calls := 0
	pid, err := tfilAncestor(200, func(pid int) (int, string, error) { calls++; return pid - 1, "codex", nil })
	if err != nil || pid != 0 || calls != 128 {
		t.Fatalf("unbounded traversal: %d, %d, %v", pid, calls, err)
	}
}

func TestTfilWrapperHeader(t *testing.T) {
	for _, tt := range []struct {
		name, content string
		want          bool
	}{
		{"generated", "#!/bin/sh\n# tfil-wrapper\nexec tfil\n", true},
		{"short", "#!/bin/sh\n# tfil-wrapper", false},
		{"later comment", "#!/bin/sh\n# custom wrapper\n# tfil-wrapper\n", false},
		{"similar marker", "#!/bin/sh\n# tfil-wrapper-other\n", false},
		{"other script", "#!/bin/sh\nexec tfil --critty-notify codex\n", false},
	} {
		t.Run(tt.name, func(t *testing.T) {
			path := filepath.Join(t.TempDir(), "codex")
			if err := os.WriteFile(path, []byte(tt.content), 0755); err != nil {
				t.Fatal(err)
			}
			if got := isTfilWrapper(path); got != tt.want {
				t.Fatalf("recognized: %v, want %v", got, tt.want)
			}
		})
	}
	if isTfilWrapper(filepath.Join(t.TempDir(), "missing")) {
		t.Fatal("recognized a missing wrapper")
	}
}

func TestDoctorNotificationRequiresRequest(t *testing.T) {
	cmd := newDoctorCommand()
	cmd.SilenceUsage = true
	cmd.SilenceErrors = true
	cmd.SetArgs([]string{"--terminal-notify-only"})
	if err := cmd.Execute(); err == nil || !strings.Contains(err.Error(), "requires --terminal-request") {
		t.Fatalf("missing request: %v", err)
	}
}
